"""Generate config/locale.h: for every character the keymap uses, the ZMK binding that types it
on the US layout and on the Windows Canadian French layout (00001009).
Run on Windows:  python tools/gen_locale.py   (re-run only if the list of characters changes)."""
import ctypes
from ctypes import wintypes
from pathlib import Path

u = ctypes.WinDLL("user32")
u.LoadKeyboardLayoutW.restype = ctypes.c_void_p
u.ToUnicodeEx.argtypes = [wintypes.UINT, wintypes.UINT, ctypes.c_char_p, wintypes.LPWSTR, ctypes.c_int,
                          wintypes.UINT, ctypes.c_void_p]
u.MapVirtualKeyExW.argtypes = [wintypes.UINT, wintypes.UINT, ctypes.c_void_p]
CAFR = u.LoadKeyboardLayoutW("00001009", 0x80)

# ZMK key name -> PC scancode (same physical positions on both layouts)
SC = {**{c: s for c, s in zip("QWERTYUIOP", range(0x10, 0x1A))},
      **{c: s for c, s in zip("ASDFGHJKL", range(0x1E, 0x27))},
      **{c: s for c, s in zip("ZXCVBNM", range(0x2C, 0x33))},
      **{f"N{d}": s for d, s in zip("1234567890", range(0x02, 0x0C))},
      "MINUS": 0x0C, "EQUAL": 0x0D, "LBKT": 0x1A, "RBKT": 0x1B, "BSLH": 0x2B, "SEMI": 0x27,
      "SQT": 0x28, "GRAVE": 0x29, "COMMA": 0x33, "DOT": 0x34, "FSLH": 0x35, "NON_US_BSLH": 0x56,
      "SPACE": 0x39}


def produce(name, shift, altgr):
    st = (ctypes.c_ubyte * 256)()
    if shift:
        st[0x10] = st[0xA0] = 0x80
    if altgr:
        st[0x11] = st[0xA2] = st[0x12] = st[0xA5] = 0x80
    vk = u.MapVirtualKeyExW(SC[name], 1, CAFR)
    b = ctypes.create_unicode_buffer(8)
    n = u.ToUnicodeEx(vk, SC[name], ctypes.cast(st, ctypes.c_char_p), b, 8, 0x4, CAFR)
    return n, b.value[:abs(n)]


def wrap(name, shift, altgr):
    k = name
    if shift:
        k = f"LS({k})"
    if altgr:
        k = f"RA({k})"
    return k


# Every character -> how to type it on Canadian French: ("kp", keycode) or ("dead", keycode) (dead key: + space)
table = {}
for name in SC:
    for shift, altgr in ((False, False), (True, False), (False, True), (True, True)):
        n, ch = produce(name, shift, altgr)
        if len(ch) == 1 and ch.isprintable() and ch != " ":
            kind = "dead" if n < 0 else "kp"
            if ch not in table or (table[ch][0] == "dead" and kind == "kp"):
                table[ch] = (kind, wrap(name, shift, altgr))

# The keymap's character keys: macro name -> (US binding normal, char normal, char with Shift or None)
# None = a single symbol key (Shift doesn't change it).
KEYS = {
    "SQT": ("'", '"'), "COMMA": (",", "<"), "DOT": (".", ">"), "FSLH": ("/", "?"), "SEMI": (";", ":"),
    "LBKT": ("[", "{"), "RBKT": ("]", "}"), "EQUAL": ("=", "+"), "GRAVE": ("`", "~"), "BSLH": ("\\", "|"),
    "MINUS": ("-", "_"),
    "N1": ("1", "!"), "N2": ("2", "@"), "N3": ("3", "#"), "N4": ("4", "$"), "N5": ("5", "%"),
    "N6": ("6", "^"), "N7": ("7", "&"), "N8": ("8", "*"), "N9": ("9", "("), "N0": ("0", ")"),
    "LBRC": ("{", None), "RBRC": ("}", None), "COLON": (":", None), "PLUS": ("+", None),
    "TILDE": ("~", None), "PIPE": ("|", None), "LPAR": ("(", None), "RPAR": (")", None),
    "UNDER": ("_", None), "LT": ("<", None), "GT": (">", None), "DQT": ('"', None), "QMARK": ("?", None),
    "CARET": ("^", None),
}

behaviors, defines = [], []


def cafr_binding(ch, label):
    """Binding for one character on Canadian French; may add a macro behavior."""
    kind, key = table[ch]
    if kind == "kp":
        return f"&kp {key}"
    # Dead key: tap it, then Space, to get the character on its own.
    mname = f"cf_{label}"
    behaviors.append(f"        CF_DEAD_SPACE({mname}, {key})")
    return f"&{mname}"


for name, (normal, shifted) in KEYS.items():
    lo = cafr_binding(normal, name.lower())
    if shifted is None:
        defines.append((name, lo))
        continue
    # Does the plain key with Shift already give the right character on Canadian French?
    natural = None
    if lo.startswith("&kp ") and "(" not in lo:
        n, natural = produce(lo[4:], True, False)
    if natural == shifted:
        defines.append((name, lo))
    else:
        up = cafr_binding(shifted, name.lower() + "_shifted")
        behaviors.append(f"        CF_SHIFT_MORPH(cf_{name.lower()}_mm, {lo}, {up})")
        defines.append((name, f"&cf_{name.lower()}_mm"))

out = ["// GENERATED by tools/gen_locale.py - do not edit by hand.",
       "// Character keys used by corne.keymap. Each one types the same character on the US layout",
       "// and, when built with -DLAYOUT_CA_FR, on the Windows Canadian French layout.",
       "#pragma once", "",
       "#if defined(LAYOUT_CA_FR)", ""]
out += [f"#define K_{n} {b}" for n, b in defines]
out += ["", "// Behaviors the Canadian French mappings need (placed inside / { behaviors { ... } })",
        "#define LOCALE_BEHAVIORS \\"]
out += [b + " \\" for b in behaviors] + ["", "#else  // US layout", ""]
out += [f"#define K_{n} &kp {n}" for n in KEYS]
out += ["", "#define LOCALE_BEHAVIORS", "", "#endif", ""]
path = Path(__file__).resolve().parent.parent / "config" / "locale.h"
path.write_text("\n".join(out), encoding="utf-8", newline="\n")
print(f"wrote {path}")
for n, b in defines:
    print(f"  K_{n:7s} {b}")
print("behaviors:"); print("\n".join(behaviors))
